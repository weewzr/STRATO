/** The case file of the parameter table: path, digest, last commit, command and the note of the file itself. */
function CaseFileTable() {
  const caseId = useStrato((s) => s.caseId);
  const entry = findCase(caseId);
  if (!entry) return null;
  const p = entry.provenance;
  const rows: { item: string; value: ReactNode }[] = [
    {
      item: 'Case file',
      value: (
        <a href={repoFile(p.input_file)}>
          <code>{p.input_file}</code>
        </a>
      ),
    },
    {
      item: 'SHA-256',
      value: <code className="hash">{p.input_sha256}</code>,
    },
    { item: 'Last commit of the file', value: <code>{p.input_commit.slice(0, 7)}</code> },
    { item: 'Generated by', value: <code>{p.command}</code> },
    { item: 'Note in the file', value: p.notes.join(' ') },
  ];
  return (
    <TableBox label="Case file of the parameter table">
      <table className="table" data-testid="provenance">
        <caption className="visually-hidden">Case file of the parameter table</caption>
        <tbody>
          {rows.map((r) => (
            <tr key={r.item}>
              <th scope="row">{r.item}</th>
              <td>{r.value}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </TableBox>
  );
}

/** The key of every parameter in the case file (the identifier that left the Data table). */
function KeyTable() {
  const caseId = useStrato((s) => s.caseId);
  const entry = findCase(caseId);
  if (!entry) return null;
  const rows = parameterRows(entry.config, entry.config, entry.provenance.input_file);
  return (
    <TableBox label="Key of every parameter in the case file">
      <table className="table" data-testid="documentation-keys">
        <caption className="visually-hidden">Key of every parameter in the case file</caption>
        <thead>
          <tr>
            <th scope="col">Parameter</th>
            <th scope="col">Key in the case file</th>
          </tr>
        </thead>
        <tbody>
          {rows.map((r) => (
            <tr key={r.key}>
              <th scope="row">{r.parameter}</th>
              <td>
                <code>{r.key}</code>
              </td>
            </tr>
          ))}
        </tbody>
      </table>
    </TableBox>
  );
}

