import { repoFile } from '../build';
import { findCase } from '../data/case';
import { Badge } from '../panels/Badge';
import { LiveDownloads } from '../panels/Downloads';
import { ParameterProvenance, References } from '../panels/Provenance';
import { useStrato } from '../state/store';
import { SectionHeading } from './common';

/** Precomputed native output of the synthetic case (web/public/data, written by strato-webtools precomputed). */
const PRECOMPUTED: { file: string; title: string; text: string }[] = [
  {
    file: 'btcs_run.timeseries.csv',
    title: 'Time series of the native BTCS run (CSV)',
    text: 'remaining inventory, cumulative release, release fraction, release rate and mass-balance residual with its derived bound at every output time, written by the solver with its provenance header.',
  },
  {
    file: 'btcs_run.profiles.csv',
    title: 'Concentration profiles of the native BTCS run (CSV)',
    text: 'concentration at every node of the grid at five times, written by the solver.',
  },
  {
    file: 'btcs_vs_analytical.csv',
    title: 'Method A against Method B (CSV)',
    text: 'the release fractions of Method A: BTCS and Method B: Sturm–Liouville and their absolute difference at every output time.',
  },
  {
    file: 'btcs_independent_check.csv',
    title: 'Independent check with the observed orders (CSV)',
    text: 'the release fraction against an independent reference at four times, with the observed orders in time and in space, copied from the regression suite.',
  },
];

/**
 * The Data section (prompt/DESIGN_SPECIFICATION.md Sections 8.4 and 8.5): the provenance of every
 * parameter in use, the downloads of the live results (web phase 5) and of the precomputed native
 * output, and the reference list.
 */
export function Data() {
  const caseId = useStrato((s) => s.caseId);
  const entry = findCase(caseId);
  if (!entry) return null;
  const p = entry.provenance;
  return (
    <article className="section" data-section="data">
      <SectionHeading lede="Where every input comes from, the results to download with their provenance, and the references.">Data and provenance</SectionHeading>

      <h2>Parameters in use</h2>
      <ParameterProvenance entry={entry} />

      <dl className="provenance" data-testid="provenance">
        <dt>Case file</dt>
        <dd>
          <a href={repoFile(p.input_file)}>
            <code>{p.input_file}</code>
          </a>
        </dd>
        <dt>SHA-256</dt>
        <dd>
          <code className="hash">{p.input_sha256}</code>
        </dd>
        <dt>Last commit of the file</dt>
        <dd>
          <code>{p.input_commit.slice(0, 7)}</code>
        </dd>
        <dt>Generated by</dt>
        <dd>
          <code>{p.command}</code>
        </dd>
        <dt>Note in the file</dt>
        <dd>{p.notes.join(' ')}</dd>
      </dl>

      <h2>Downloads of the live results</h2>
      <p>
        Written by the solver in Rust, in this browser, each file starting with a provenance header: the solver and its version, the commit of
        the WebAssembly solver build, the digest of the input, and the source row and class of the parameters. Every column is named in full
        with its unit. Numbers are written in the shortest form that reads back to the same value, so a file reproduces the plotted values
        exactly. Each figure can also be saved as SVG or PNG with its source line.
      </p>
      <LiveDownloads />

      <h2>Precomputed native output and inputs</h2>
      <ul className="prose-list">
        <li>
          <a href={`${import.meta.env.BASE_URL}${entry.csvPath}`} download data-testid="download-case">
            Case inputs (CSV)
          </a>
          , with a provenance header: generator, STRATO version, case file, SHA-256 and commit.
        </li>
        {PRECOMPUTED.map((f) => (
          <li key={f.file}>
            <a href={`${import.meta.env.BASE_URL}data/${f.file}`} download data-testid={`download-${f.file}`}>
              {f.title}
            </a>{' '}
            <Badge label="PRECOMPUTED" />: {f.text}
          </li>
        ))}
        <li>
          <a href={`${import.meta.env.BASE_URL}data/agr1_reference_geometry.csv`} download data-testid="download-agr1-geometry">
            AGR-1 reference-particle geometry (CSV)
          </a>
          : the registered kernel diameter and coating thicknesses of each AGR-1 set with row ids, status, source, location in the
          source and public link where the register holds one, and the outer radii drawn by the reference view; written from{' '}
          <code>data/geometry/geometry.csv</code> by <code>strato-webtools geometry</code>. Registered geometry, not a
          simulation.
        </li>
      </ul>
      <p>
        The precomputed files are written by <code>strato-webtools precomputed</code> from the native release build of the BTCS solver; each
        starts with a provenance header (solver, solver version, commit, input file and its SHA-256, command, toolchain), and continuous
        integration regenerates them and fails if they differ. In every generated file, including the AGR-1 geometry file, the commit in the
        header is the source commit the file was generated from: a file cannot record the commit that contains it. The AGR-1 geometry file
        also records the SHA-256 of the generator that wrote it, and its commit carries the suffix <code>+modified</code> if the generator or
        its input differed from that commit.
      </p>

      <h2>References</h2>
      <References />
    </article>
  );
}
